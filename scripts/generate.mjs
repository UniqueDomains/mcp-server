#!/usr/bin/env node
/*----------------------------------
- GENERATE THE TOOLS
----------------------------------*/

/**
 * Builds `src/generated/tools.ts` and the README's tool list from the API document the installed SDK ships
 * (`@uniquedomains/sdk/openapi.json`) and its operation table, and copies that document to `openapi/v1.json` so a
 * change to the tools shows next to the change of the document behind it.
 *
 *   npm run generate              write the three files
 *   npm run generate -- --check   fail when a committed file differs from what the installed SDK gives (CI)
 *   npm run generate -- --live    fail when the live document differs from `openapi/v1.json` (the nightly contract)
 */

import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { isDeepStrictEqual } from 'node:util';
import { OPERATIONS, API_PUBLIC_BASE } from '@uniquedomains/sdk';

import { buildTools } from './lib/tools.mjs';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const SDK_DOCUMENT = join(ROOT, 'node_modules', '@uniquedomains', 'sdk', 'openapi.json');
const SNAPSHOT = join(ROOT, 'openapi', 'v1.json');
const TOOLS_FILE = join(ROOT, 'src', 'generated', 'tools.ts');
const README = join(ROOT, 'README.md');
const README_START = '<!-- tools:start (generated by scripts/generate.mjs) -->';
const README_END = '<!-- tools:end -->';

const args = new Set(process.argv.slice(2));

const readJson = async (path) => JSON.parse(await readFile(path, 'utf8'));
const readText = async (path) => {
    try {
        return await readFile(path, 'utf8');
    } catch {
        return null;
    }
};

const sdkVersion = (await readJson(join(ROOT, 'node_modules', '@uniquedomains', 'sdk', 'package.json'))).version;
const document = await readJson(SDK_DOCUMENT);

if (args.has('--live')) {
    const response = await fetch(`${API_PUBLIC_BASE}/meta/openapi.json`, { headers: { 'User-Agent': 'uniquedomains-mcp-server-contract' } });
    if (!response.ok) throw new Error(`The live document answered ${response.status}.`);
    const live = await response.json();
    const snapshot = await readJson(SNAPSHOT);
    if (isDeepStrictEqual(live, snapshot)) {
        console.log('The live document matches openapi/v1.json.');
    } else {
        console.error('The live document differs from openapi/v1.json: update @uniquedomains/sdk once it ships the new document, then run `npm run generate`.');
        process.exitCode = 1;
    }
    process.exit();
}

const tools = buildTools(OPERATIONS, document);

/* ---------- src/generated/tools.ts ---------- */

const toolsSource = [
    '/*----------------------------------',
    '- GENERATED: do not edit. `npm run generate` writes this file from @uniquedomains/sdk.',
    '----------------------------------*/',
    '',
    "import type { ToolDefinition } from '../tool';",
    '',
    `/** The API document version and the SDK version the tools were generated from. */`,
    `export const TOOLS_DOCUMENT_VERSION = ${JSON.stringify(document.info.version)};`,
    `export const TOOLS_SDK_VERSION = ${JSON.stringify(sdkVersion)};`,
    '',
    '/** Every tool of the server, in the document order. */',
    `export const TOOLS: readonly ToolDefinition[] = ${JSON.stringify(tools, null, 4)};`,
    '',
].join('\n');

/* ---------- README tool list ---------- */

const row = (tool) => {
    const access = tool.tier === 'free' ? (tool.hosted ? 'free' : 'free, npm only') : tool.plan === 'investor' ? 'Investor key' : 'member key';
    return `| \`${tool.name}\` | ${tool.title} | ${access} |`;
};
const counts = {
    local: tools.filter((tool) => tool.tier === 'free').length,
    hosted: tools.filter((tool) => tool.hosted).length,
    keyed: tools.filter((tool) => tool.tier === 'keyed').length,
};
const toolList = [
    README_START,
    '',
    `${counts.local} tools answer without a key (${counts.hosted} on the hosted connector); a member key adds ${counts.keyed} more, the Investor ones for an Investor key only.`,
    '',
    '| Tool | What it reads | Needs |',
    '|---|---|---|',
    ...tools.map(row),
    '',
    README_END,
].join('\n');

const currentReadme = await readText(README);
const replaceToolList = (readme) => {
    const start = readme.indexOf(README_START);
    const end = readme.indexOf(README_END);
    if (start === -1 || end === -1) throw new Error('README.md has no tool list markers.');
    return readme.slice(0, start) + toolList + readme.slice(end + README_END.length);
};
const nextReadme = currentReadme === null ? null : replaceToolList(currentReadme);
const snapshotText = `${JSON.stringify(document, null, 2)}\n`;

if (args.has('--check')) {
    const stale = [];
    if ((await readText(TOOLS_FILE)) !== toolsSource) stale.push('src/generated/tools.ts');
    if ((await readText(SNAPSHOT)) !== snapshotText) stale.push('openapi/v1.json');
    if (currentReadme !== nextReadme) stale.push('README.md (tool list)');
    if (stale.length > 0) {
        console.error(`Out of date, run \`npm run generate\`: ${stale.join(', ')}`);
        process.exitCode = 1;
    } else {
        console.log(`The generated files match @uniquedomains/sdk ${sdkVersion} (${tools.length} tools).`);
    }
} else {
    await mkdir(dirname(TOOLS_FILE), { recursive: true });
    await mkdir(dirname(SNAPSHOT), { recursive: true });
    await writeFile(TOOLS_FILE, toolsSource);
    await writeFile(SNAPSHOT, snapshotText);
    if (nextReadme !== null) await writeFile(README, nextReadme);
    console.log(`Wrote ${tools.length} tools from @uniquedomains/sdk ${sdkVersion} (${counts.local} free, ${counts.hosted} hosted, ${counts.keyed} keyed).`);
}
